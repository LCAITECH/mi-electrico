export function plugsIn(kind: Powertrain) {
  return kind === "ev" || kind === "phev";
}

/** kWh/100 para la parte eléctrica. La prueba manda si existe; si no, el ciclo de la ficha. */
export function electricKwhPer100(car: CarModel): { value: number; basis: string } | null {
  if (!plugsIn(car.kind) || !car.batteryKwh) return null;
  if (car.testKwhPer100) return { value: car.testKwhPer100, basis: "prueba a 100 km/h, no es el ciclo" };
  if (car.rangeKm && car.rangeKm > 0 && car.rangeKm < 700) {
    return {
      value: (car.batteryKwh / car.rangeKm) * 100,
      basis: `ciclo ${car.rangeCycle ?? "sin nombre"}`,
    };
  }
  return null;
}

export function ars(value: number) {
  return new Intl.NumberFormat("es-AR", {
    style: "currency",
    currency: "ARS",
    maximumFractionDigits: 0,
  }).format(value);
}

export function usd(value: number) {
  return new Intl.NumberFormat("es-AR", {
    style: "currency",
    currency: "USD",
    maximumFractionDigits: 0,
  }).format(value);
}

export function num(value: number, digits = 0) {
  return new Intl.NumberFormat("es-AR", {
    maximumFractionDigits: digits,
    minimumFractionDigits: digits,
  }).format(value);
}
